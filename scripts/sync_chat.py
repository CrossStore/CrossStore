#!/usr/bin/env python3
"""Generate standalone chat entry points from their shared Lua UI source."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
body=(ROOT/'shared/chat_ui.lua').read_text()
for ident,transport in [('rf_chat','radio'),('wifi_chat','wifi'),('esp_chat','esp_now')]:
    text=f'-- Generated by scripts/sync_chat.py; edit shared/chat_ui.lua.\nlocal transport,application_name="{transport}","{ident}"\n'+body
    (ROOT/'packages'/ident/'main.lua').write_text(text)
